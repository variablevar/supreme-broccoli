const sourceKeyByPhrase = new Map(
  Object.entries(en).map(([key, value]) => [normalizePhrase(value), key as Key])
);

const sourcePhraseByTranslation = new Map<string, string>();

Object.values(en).forEach((value) => {
  sourcePhraseByTranslation.set(normalizePhrase(value), value);
});

Object.entries(runtimePhrases).forEach(([source, translations]) => {
  sourcePhraseByTranslation.set(source, source);
  Object.values(translations).forEach((value) => {
    if (value) sourcePhraseByTranslation.set(normalizePhrase(value), source);
  });
});

export function normalizePhrase(value: string) {
  return value.replace(/\s+/g, ' ').trim().toLowerCase();
}

export function sourcePhrase(value: string) {
  return sourcePhraseByTranslation.get(normalizePhrase(value)) ?? value;
}

export function translatePhrase(language: LanguageCode, value: string) {
  const source = sourcePhrase(value);
  const normalized = normalizePhrase(source);
  if (!normalized) return value;
  if (language === 'en-GB' || language === 'en-US') return source;

  const exact = runtimePhrases[normalized]?.[language];
  if (exact) return exact;

  const sourceKey = sourceKeyByPhrase.get(normalized);
  if (sourceKey) {
    const translated = translate(language, sourceKey);
    if (translated !== en[sourceKey]) return translated;
  }

  return value;
}

export function isRtlLanguage(language: LanguageCode) {
  return language === 'ar' || language === 'ur' || language === 'pk';
}
